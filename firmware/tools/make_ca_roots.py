#!/usr/bin/env python3
"""Regenerate AvianFrame/ca_roots.h from the system CA store.

The frame checks HTTPS certificates against this short list of big public
roots (GitHub Pages, healthchecks.io and most of the web chain to one of them).
CI verifies the live site still chains to this list (firmware.yml).

    python3 firmware/tools/make_ca_roots.py [--pem out.pem]
"""
import argparse
from pathlib import Path

ROOTS = [
    "ISRG_Root_X1", "ISRG_Root_X2",                       # Let's Encrypt
    "USERTrust_RSA_Certification_Authority",              # Sectigo
    "USERTrust_ECC_Certification_Authority",
    "Sectigo_Public_Server_Authentication_Root_R46",
    "Sectigo_Public_Server_Authentication_Root_E46",
    "DigiCert_Global_Root_G2", "DigiCert_Global_Root_G3",
    "DigiCert_Global_Root_CA",                            # may be absent on newer stores
    "GlobalSign_Root_CA_-_R3", "GlobalSign_Root_R46", "GlobalSign_Root_E46",
]

ap = argparse.ArgumentParser()
ap.add_argument("--certs", default="/etc/ssl/certs")
ap.add_argument("--pem", help="also write the bundle as a PEM file")
a = ap.parse_args()

pems, used = [], []
for name in ROOTS:
    p = Path(a.certs) / f"{name}.pem"
    if p.exists():
        pems.append(p.read_text().strip())
        used.append(name)
bundle = "\n".join(pems) + "\n"
out = Path(__file__).resolve().parents[1] / "AvianFrame" / "ca_roots.h"
body = "\n".join(f'"{line}\\n"' for line in bundle.splitlines())
out.write_text("// Generated by firmware/tools/make_ca_roots.py - public root certificates.\n"
               f"// {', '.join(used)}\n#pragma once\nstatic const char CA_ROOTS[] =\n{body};\n")
if a.pem:
    Path(a.pem).write_text(bundle)
print(f"{len(used)} roots -> {out}")
